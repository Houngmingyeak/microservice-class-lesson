package kh.edu.istad.platform.business.domain.usecase;

import kh.edu.istad.common.domain.Money;
import kh.edu.istad.platform.business.domain.dto.ProductCommand;
import kh.edu.istad.platform.business.domain.dto.ProductResult;
import kh.edu.istad.platform.business.domain.dto.RegisterBusinessCommand;
import kh.edu.istad.platform.business.domain.dto.RegisterBusinessResult;
import kh.edu.istad.platform.business.domain.entity.Business;
import kh.edu.istad.platform.business.domain.entity.Product;
import kh.edu.istad.platform.business.domain.exception.BusinessAlreadyExistsException;
import kh.edu.istad.platform.business.domain.exception.BusinessDomainException;
import kh.edu.istad.platform.business.domain.port.out.BusinessRepository;
import kh.edu.istad.platform.business.domain.service.BusinessDomainService;
import kh.edu.istad.platform.business.domain.valueobject.BusinessContact;
import kh.edu.istad.platform.business.domain.valueobject.BusinessName;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Component;
import reactor.core.publisher.Mono;

import java.util.ArrayList;
import java.util.List;

@Component
@Slf4j
@RequiredArgsConstructor
public class RegisterBusinessUseCase {

    private final BusinessDomainService businessDomainService;
    private final BusinessRepository businessRepository;

    public Mono<RegisterBusinessResult> execute(RegisterBusinessCommand command) {
        log.info("register business usecase: {}", command);

        if (command.email() == null) {
            return Mono.error(new BusinessDomainException("Business email must not be null"));
        }

        // validate by loading data from persistence (output port)
        return businessRepository.existsByEmail(command.email())
                .flatMap(emailExists -> {
                    if (emailExists) {
                        return Mono.<Business>error(new BusinessAlreadyExistsException(
                                "A business with email " + command.email() + " already exists"));
                    }

                    // build the products from the command (ids are generated by the domain)
                    List<Product> products = new ArrayList<>();
                    if (command.products() != null) {
                        for (ProductCommand productCommand : command.products()) {
                            int quantity = 0;
                            if (productCommand.quantity() != null) {
                                quantity = productCommand.quantity();
                            }
                            Product product = new Product(
                                    productCommand.name(),
                                    new Money(productCommand.price()),
                                    quantity,
                                    Boolean.TRUE.equals(productCommand.available())
                            );
                            products.add(product);
                        }
                    }

                    // build the domain object (id and active stay empty on purpose)
                    Business business = Business.Builder.builder()
                            .businessName(new BusinessName(command.legalName(), command.displayName()))
                            .businessContact(new BusinessContact(command.email(), command.phoneNumber()))
                            .products(products)
                            .build();

                    // invoke domain logic: validates the business, generates ids, sets it active
                    businessDomainService.validateAndRegisterBusiness(business);

                    // save data into the database (output port)
                    return businessRepository.save(business);
                })
                .map(savedBusiness -> {
                    List<ProductResult> productResults = new ArrayList<>();
                    for (Product product : savedBusiness.getProducts()) {
                        ProductResult productResult = new ProductResult(
                                product.getId().value(),
                                product.getName(),
                                product.getPrice().amount(),
                                product.getQuantity(),
                                product.isAvailable()
                        );
                        productResults.add(productResult);
                    }
                    return new RegisterBusinessResult(
                            savedBusiness.getId().value(),
                            savedBusiness.getBusinessName().legalName(),
                            savedBusiness.getBusinessName().displayName(),
                            savedBusiness.getBusinessContact().email(),
                            savedBusiness.getBusinessContact().phoneNumber(),
                            savedBusiness.isActive(),
                            productResults,
                            "Business registered successfully"
                    );
                });
    }

}
