package kh.edu.istad.platform.business.domain.entity;

import kh.edu.istad.common.domain.Money;
import kh.edu.istad.common.domain.entity.BaseEntity;
import kh.edu.istad.platform.business.domain.exception.BusinessDomainException;
import kh.edu.istad.platform.business.domain.valueobject.ProductId;

import java.math.BigDecimal;
import java.util.UUID;

public class Product extends BaseEntity<ProductId> {

    private final String name;
    private final Money price;
    private final int quantity;
    private final boolean available;

    // used when a new product is registered (the id is generated by the Business)
    public Product(String name, Money price, int quantity, boolean available) {
        this.name = name;
        this.price = price;
        this.quantity = quantity;
        this.available = available;
    }

    // used when a product is loaded from the database or comes from an order
    public Product(ProductId productId, String name, Money price, int quantity, boolean available) {
        super.setId(productId);
        this.name = name;
        this.price = price;
        this.quantity = quantity;
        this.available = available;
    }

    void initializeProduct() {
        super.setId(new ProductId(UUID.randomUUID()));
    }

    void validateProduct() {
        if (name == null || name.isBlank()) {
            throw new BusinessDomainException("Product name must not be blank");
        }
        if (price == null || price.amount() == null || price.amount().compareTo(BigDecimal.ZERO) <= 0) {
            throw new BusinessDomainException("Price of product " + name + " must be greater than zero");
        }
        if (quantity < 0) {
            throw new BusinessDomainException("Quantity of product " + name + " must not be negative");
        }
    }

    public String getName() {
        return name;
    }

    public Money getPrice() {
        return price;
    }

    public int getQuantity() {
        return quantity;
    }

    public boolean isAvailable() {
        return available;
    }
}
